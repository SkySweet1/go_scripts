def add(x, y):
    while y != 0:
        ones = x & y
        x = x ^ y
        y = ones << 1
        
    return x

#   while y != 0:           пока есть переносы. если Y = 0 то все переносы обработанны
#   
#   ones = x & y           находим биты где у Y и X стоят еденицы (обязательно возникает перенос)
#   
#   x = x ^ y               это обычно сложение без учета переносов т е 1+1=0 
#   
#   y = ones << 1          берем переносы и сдвигаем налево потомучто перенос из мдадшего разряда идет в следующий (более старший)
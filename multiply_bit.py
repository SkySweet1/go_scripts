def multiply(a, b):
    result = 0
    
    while b > 0:
        if b & 1:
            result = add(result, a)
        
        a <<= 1
        b >>= 1
    
    return result

#   if b & 1:                   проверка на младший бит = 1 ?
#   
#   result = add(result, a)     сложение двух чисел без оператора "+"
#   
#   в multiply() не нужны обработки переносов потомучто они уже обрабатываються в add()
#   
#   a <<= 1   b >>= 1           сдвигает a и b
